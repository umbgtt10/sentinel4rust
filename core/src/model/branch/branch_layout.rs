//! The files and the commit message one publication writes in the results repository
//! (`ADR-SharedResultsRepository`): the repository's own folder, and the README at the root.

use crate::model::branch::branch_file::BranchFile;
use crate::model::branch::publication::Publication;
use crate::model::branch::summary_toml::SummaryToml;
use crate::model::outcome_kind::OutcomeKind;
use alloc::format;
use alloc::string::String;
use alloc::string::ToString;
use alloc::vec;
use alloc::vec::Vec;

/// The `README.md` written at the root of the results repository.
const RESULTS_README: &str = "\
# mutants

Generated by [sentinel4rust](https://github.com/umbgtt10/sentinel4rust). **Do not edit by hand.**

One folder per watched repository. Each holds the result of the latest full mutation-testing run
([cargo-mutants](https://mutants.rs)) against the commit named in its `summary.toml`:

- `summary.toml` -- the commit, times, outcome, counts, versions and the test timeout cargo-mutants set;
- `missed.txt` -- surviving mutants, one per line, without line numbers so the history diffs cleanly;
- `timeout.txt` -- mutants whose tests timed out (absent when none);
- `located/` -- the same lists with `file:line:col`.

`git log -p -- <repo>/` is the history of one repository's survivors.
";

/// The files and the commit message one publication writes in the results repository.
#[derive(Debug, Clone, Copy, Default)]
pub struct BranchLayout;

impl BranchLayout {
    /// The files to write, in a fixed order: the root's README, then `folder`'s files, which replace whatever
    /// the folder held.
    pub fn files(&self, folder: &str, publication: &Publication) -> Vec<BranchFile> {
        let mut files = vec![
            BranchFile {
                path: "README.md".to_string(),
                contents: RESULTS_README.to_string(),
            },
            Self::file(
                folder,
                "summary.toml",
                SummaryToml.render(&publication.record),
            ),
        ];
        if publication.record.outcome == OutcomeKind::Completed {
            files.push(Self::file(
                folder,
                "missed.txt",
                Self::lines(publication.missed.iter().map(ToString::to_string)),
            ));
            files.push(Self::file(
                folder,
                "located/missed.txt",
                Self::lines(publication.located_missed.iter().cloned()),
            ));
            if !publication.timed_out.is_empty() {
                files.push(Self::file(
                    folder,
                    "timeout.txt",
                    Self::lines(publication.timed_out.iter().map(ToString::to_string)),
                ));
                files.push(Self::file(
                    folder,
                    "located/timeout.txt",
                    Self::lines(publication.located_timed_out.iter().cloned()),
                ));
            }
        }
        files
    }

    /// The commit message, led by `folder` (`ADR-SharedResultsRepository`): a completed run's timeouts are named
    /// when there are any, so one whose mutants mostly timed out does not read as a clean run.
    pub fn message(&self, folder: &str, publication: &Publication) -> String {
        let r = &publication.record;
        let short = r.commit.short();
        match r.outcome {
            OutcomeKind::Completed if r.counts.timeout > 0 => format!(
                "{folder}: Mutants of {short}: {} missed (+{} -{}), {} caught, {} timed out",
                r.counts.missed, r.new, r.gone, r.counts.caught, r.counts.timeout
            ),
            OutcomeKind::Completed => format!(
                "{folder}: Mutants of {short}: {} missed (+{} -{}), {} caught",
                r.counts.missed, r.new, r.gone, r.counts.caught
            ),
            OutcomeKind::BaselineFailed => format!("{folder}: Mutants of {short}: baseline failed"),
            OutcomeKind::ToolFailed => format!("{folder}: Mutants of {short}: tool failed"),
        }
    }

    fn file(folder: &str, path: &str, contents: String) -> BranchFile {
        BranchFile {
            path: format!("{folder}/{path}"),
            contents,
        }
    }

    fn lines(items: impl Iterator<Item = String>) -> String {
        items.map(|item| item + "\n").collect()
    }
}
