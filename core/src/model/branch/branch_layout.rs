//! The files and the commit message one publication writes on `mutants` (`ADR-OrphanMutantsBranch`).

use crate::model::branch::branch_file::BranchFile;
use crate::model::branch::publication::Publication;
use crate::model::branch::summary_toml::SummaryToml;
use crate::model::outcome_kind::OutcomeKind;
use alloc::format;
use alloc::string::String;
use alloc::string::ToString;
use alloc::vec;
use alloc::vec::Vec;

/// The `README.md` written on the `mutants` branch.
const BRANCH_README: &str = "\
# mutants

This branch is generated by [sentinel4rust](https://github.com/umbgtt10/sentinel4rust). **Do not merge it.**

It shares no history with `main`. Each commit holds the result of a full mutation-testing run
([cargo-mutants](https://mutants.rs)) against the `main` commit named in `summary.toml`:

- `summary.toml` -- the commit, times, outcome, counts and versions;
- `missed.txt` -- surviving mutants, one per line, without line numbers so the history diffs cleanly;
- `timeout.txt` -- mutants whose tests timed out (absent when none);
- `located/` -- the same lists with `file:line:col`.

`git log -p` on this branch is the history of the survivors.
";

/// The files and the commit message one publication writes on `mutants`.
#[derive(Debug, Clone, Copy, Default)]
pub struct BranchLayout;

impl BranchLayout {
    /// The files to write, in a fixed order.
    pub fn files(&self, publication: &Publication) -> Vec<BranchFile> {
        let mut files = vec![
            Self::file("README.md", BRANCH_README.to_string()),
            Self::file("summary.toml", SummaryToml.render(&publication.record)),
        ];
        if publication.record.outcome == OutcomeKind::Completed {
            files.push(Self::file(
                "missed.txt",
                Self::lines(publication.missed.iter().map(ToString::to_string)),
            ));
            files.push(Self::file(
                "located/missed.txt",
                Self::lines(publication.located_missed.iter().cloned()),
            ));
            if !publication.timed_out.is_empty() {
                files.push(Self::file(
                    "timeout.txt",
                    Self::lines(publication.timed_out.iter().map(ToString::to_string)),
                ));
                files.push(Self::file(
                    "located/timeout.txt",
                    Self::lines(publication.located_timed_out.iter().cloned()),
                ));
            }
        }
        files
    }

    /// The commit message (`ADR-OrphanMutantsBranch`): a completed run's timeouts are named when there are any, so
    /// one whose mutants mostly timed out does not read as a clean run.
    pub fn message(&self, publication: &Publication) -> String {
        let r = &publication.record;
        let short = r.commit.short();
        match r.outcome {
            OutcomeKind::Completed if r.counts.timeout > 0 => format!(
                "Mutants of {short}: {} missed (+{} -{}), {} caught, {} timed out",
                r.counts.missed, r.new, r.gone, r.counts.caught, r.counts.timeout
            ),
            OutcomeKind::Completed => format!(
                "Mutants of {short}: {} missed (+{} -{}), {} caught",
                r.counts.missed, r.new, r.gone, r.counts.caught
            ),
            OutcomeKind::BaselineFailed => format!("Mutants of {short}: baseline failed"),
            OutcomeKind::ToolFailed => format!("Mutants of {short}: tool failed"),
        }
    }

    fn file(path: &str, contents: String) -> BranchFile {
        BranchFile {
            path: path.to_string(),
            contents,
        }
    }

    fn lines(items: impl Iterator<Item = String>) -> String {
        items.map(|item| item + "\n").collect()
    }
}
