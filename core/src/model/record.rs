//! What the `mutants` branch holds for one commit (design 2.2).

use std::fmt;

use crate::model::commit_hash::CommitHash;
use crate::model::counts::MutantCounts;
use crate::model::mutant_key::MutantKey;
use crate::model::outcome::OutcomeKind;
use crate::model::timestamp::Timestamp;
use crate::model::toml::toml_error::TomlError;
use crate::model::toml::toml_parser::TomlParser;
use crate::model::toml::toml_writer::TomlWriter;

/// The `summary.toml` schema this version writes and understands.
pub const SCHEMA: i64 = 1;

/// The only run kind so far (incremental runs are an idea for later).
pub const KIND_FULL: &str = "full";

/// The contents of `summary.toml`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RunRecord {
    /// The commit tested.
    pub commit: CommitHash,
    /// The roster's `config_version` at the time.
    pub config_version: i64,
    /// `full`.
    pub kind: String,
    /// What was published.
    pub outcome: OutcomeKind,
    /// When the run started.
    pub started: Timestamp,
    /// When the run finished.
    pub finished: Timestamp,
    /// The counts (zero unless completed).
    pub counts: MutantCounts,
    /// Survivors not in the previous record.
    pub new: u64,
    /// Survivors of the previous record no longer present.
    pub gone: u64,
    /// `cargo mutants --version`.
    pub cargo_mutants_version: String,
    /// `rustc --version`.
    pub rustc_version: String,
    /// The arguments given to cargo.
    pub arguments: String,
    /// For `tool-failed`: why.
    pub reason: Option<String>,
    /// For failures: the end of the log.
    pub log_tail: Option<String>,
}

/// Why a `summary.toml` could not be used.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RecordError {
    /// Written by a newer version of the tool; treated as no record, so the commit is run again.
    UnknownSchema(i64),
    /// Not valid.
    Invalid(String),
}

impl fmt::Display for RecordError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnknownSchema(schema) => write!(f, "unknown summary schema {schema}"),
            Self::Invalid(message) => write!(f, "invalid summary: {message}"),
        }
    }
}

impl From<TomlError> for RecordError {
    fn from(error: TomlError) -> Self {
        Self::Invalid(error.to_string())
    }
}

impl RunRecord {
    /// Whether this record answers for `head` under `config_version` (design 2.1).
    pub fn is_current(&self, head: &CommitHash, config_version: i64) -> bool {
        &self.commit == head && self.config_version == config_version
    }

    /// The `summary.toml` text.
    pub fn to_toml(&self) -> String {
        let mut out = String::from("# Generated by sentinel4rust. Do not edit, do not merge.\n");
        let mut line = |key: &str, value: String| {
            out.push_str(key);
            out.push_str(" = ");
            out.push_str(&value);
            out.push('\n');
        };
        line("schema", SCHEMA.to_string());
        line("commit", TomlWriter.quote(self.commit.as_str()));
        line("config_version", self.config_version.to_string());
        line("kind", TomlWriter.quote(&self.kind));
        line("outcome", TomlWriter.quote(self.outcome.as_str()));
        line("started", TomlWriter.quote(&self.started.to_string()));
        line("finished", TomlWriter.quote(&self.finished.to_string()));
        line(
            "duration_seconds",
            self.finished.since(self.started).as_secs().to_string(),
        );
        line("caught", self.counts.caught.to_string());
        line("missed", self.counts.missed.to_string());
        line("timeout", self.counts.timeout.to_string());
        line("unviable", self.counts.unviable.to_string());
        line("new", self.new.to_string());
        line("gone", self.gone.to_string());
        line(
            "cargo_mutants_version",
            TomlWriter.quote(&self.cargo_mutants_version),
        );
        line("rustc_version", TomlWriter.quote(&self.rustc_version));
        line("arguments", TomlWriter.quote(&self.arguments));
        if let Some(reason) = &self.reason {
            line("reason", TomlWriter.quote(reason));
        }
        if let Some(tail) = &self.log_tail {
            line("log_tail", TomlWriter.quote(tail));
        }
        out
    }

    /// Parses `summary.toml`.
    pub fn parse(text: &str) -> Result<Self, RecordError> {
        let doc = TomlParser.parse(text)?;
        let t = &doc.root;
        let schema = t.required_integer("schema")?;
        if schema != SCHEMA {
            return Err(RecordError::UnknownSchema(schema));
        }
        let commit = t.required_string("commit")?;
        let commit = CommitHash::parse(&commit)
            .ok_or_else(|| RecordError::Invalid(format!("bad commit `{commit}`")))?;
        let outcome = t.required_string("outcome")?;
        let outcome = OutcomeKind::parse(&outcome)
            .ok_or_else(|| RecordError::Invalid(format!("bad outcome `{outcome}`")))?;
        let time = |key: &str| -> Result<Timestamp, RecordError> {
            let text = t.required_string(key)?;
            Timestamp::parse(&text)
                .ok_or_else(|| RecordError::Invalid(format!("bad time `{text}` for `{key}`")))
        };
        let count = |key: &str| -> Result<u64, RecordError> {
            u64::try_from(t.required_integer(key)?)
                .map_err(|_| RecordError::Invalid(format!("negative `{key}`")))
        };
        Ok(Self {
            commit,
            config_version: t.required_integer("config_version")?,
            kind: t.required_string("kind")?,
            outcome,
            started: time("started")?,
            finished: time("finished")?,
            counts: MutantCounts {
                caught: count("caught")?,
                missed: count("missed")?,
                timeout: count("timeout")?,
                unviable: count("unviable")?,
            },
            new: count("new")?,
            gone: count("gone")?,
            cargo_mutants_version: t.required_string("cargo_mutants_version")?,
            rustc_version: t.required_string("rustc_version")?,
            arguments: t.required_string("arguments")?,
            reason: t.string("reason")?,
            log_tail: t.string("log_tail")?,
        })
    }
}

/// Everything written to `mutants` for one commit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Publication {
    /// `summary.toml`.
    pub record: RunRecord,
    /// `missed.txt`, by key, sorted.
    pub missed: Vec<MutantKey>,
    /// `timeout.txt`, by key, sorted; not written when empty.
    pub timed_out: Vec<MutantKey>,
    /// `located/missed.txt`, as cargo-mutants wrote it.
    pub located_missed: Vec<String>,
    /// `located/timeout.txt`, as cargo-mutants wrote it.
    pub located_timed_out: Vec<String>,
}

/// The `README.md` written on the `mutants` branch.
pub const BRANCH_README: &str = "\
# mutants

This branch is generated by [sentinel4rust](https://github.com/umbgtt10/sentinel4rust). **Do not merge it.**

It shares no history with `main`. Each commit holds the result of a full mutation-testing run
([cargo-mutants](https://mutants.rs)) against the `main` commit named in `summary.toml`:

- `summary.toml` -- the commit, times, outcome, counts and versions;
- `missed.txt` -- surviving mutants, one per line, without line numbers so the history diffs cleanly;
- `timeout.txt` -- mutants whose tests timed out (absent when none);
- `located/` -- the same lists with `file:line:col`.

`git log -p` on this branch is the history of the survivors.
";

impl Publication {
    /// The files to write, as (path, contents), in a fixed order.
    pub fn files(&self) -> Vec<(String, String)> {
        let lines = |items: &mut dyn Iterator<Item = String>| -> String {
            items.map(|item| item + "\n").collect()
        };
        let mut files = vec![
            ("README.md".to_string(), BRANCH_README.to_string()),
            ("summary.toml".to_string(), self.record.to_toml()),
        ];
        if self.record.outcome == OutcomeKind::Completed {
            files.push((
                "missed.txt".to_string(),
                lines(&mut self.missed.iter().map(ToString::to_string)),
            ));
            files.push((
                "located/missed.txt".to_string(),
                lines(&mut self.located_missed.iter().cloned()),
            ));
            if !self.timed_out.is_empty() {
                files.push((
                    "timeout.txt".to_string(),
                    lines(&mut self.timed_out.iter().map(ToString::to_string)),
                ));
                files.push((
                    "located/timeout.txt".to_string(),
                    lines(&mut self.located_timed_out.iter().cloned()),
                ));
            }
        }
        files
    }

    /// The commit message (design 2.2).
    pub fn message(&self) -> String {
        let r = &self.record;
        let short = r.commit.short();
        match r.outcome {
            OutcomeKind::Completed => format!(
                "Mutants of {short}: {} missed (+{} -{}), {} caught",
                r.counts.missed, r.new, r.gone, r.counts.caught
            ),
            OutcomeKind::BaselineFailed => format!("Mutants of {short}: baseline failed"),
            OutcomeKind::ToolFailed => format!("Mutants of {short}: tool failed"),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    pub(crate) fn record(outcome: OutcomeKind) -> RunRecord {
        RunRecord {
            commit: CommitHash::parse(&"ab".repeat(20)).unwrap(),
            config_version: 2,
            kind: KIND_FULL.to_string(),
            outcome,
            started: Timestamp::from_unix(1_792_800_000),
            finished: Timestamp::from_unix(1_792_803_600),
            counts: MutantCounts {
                caught: 10,
                missed: 2,
                timeout: 1,
                unviable: 3,
            },
            new: 1,
            gone: 0,
            cargo_mutants_version: "cargo-mutants 27.1.0".to_string(),
            rustc_version: "rustc 1.97.0".to_string(),
            arguments: "mutants --jobs 2".to_string(),
            reason: None,
            log_tail: None,
        }
    }

    #[test]
    fn round_trips_through_toml() {
        let mut r = record(OutcomeKind::ToolFailed);
        r.reason = Some("exit 70".to_string());
        r.log_tail = Some("error: \"x\"\n\tat y\n".to_string());
        let text = r.to_toml();
        assert!(text.contains("duration_seconds = 3600"));
        assert_eq!(RunRecord::parse(&text).unwrap(), r);
        let plain = record(OutcomeKind::Completed);
        assert_eq!(RunRecord::parse(&plain.to_toml()).unwrap(), plain);
    }

    #[test]
    fn unknown_schema_and_garbage_are_errors() {
        let text = record(OutcomeKind::Completed)
            .to_toml()
            .replace("schema = 1", "schema = 2");
        assert_eq!(RunRecord::parse(&text), Err(RecordError::UnknownSchema(2)));
        assert!(matches!(
            RunRecord::parse("schema = 1"),
            Err(RecordError::Invalid(_))
        ));
        assert!(matches!(
            RunRecord::parse("[x"),
            Err(RecordError::Invalid(_))
        ));
    }

    #[test]
    fn current_needs_commit_and_config_version() {
        let r = record(OutcomeKind::Completed);
        let other = CommitHash::parse(&"cd".repeat(20)).unwrap();
        assert!(r.is_current(&r.commit, 2));
        assert!(!r.is_current(&r.commit, 3));
        assert!(!r.is_current(&other, 2));
    }

    fn publication(outcome: OutcomeKind, timed_out: bool) -> Publication {
        Publication {
            record: record(outcome),
            missed: vec![MutantKey::new("a"), MutantKey::new("b")],
            timed_out: if timed_out {
                vec![MutantKey::new("t")]
            } else {
                vec![]
            },
            located_missed: vec!["x:1:1: a".to_string(), "x:2:1: b".to_string()],
            located_timed_out: if timed_out {
                vec!["x:3:1: t".to_string()]
            } else {
                vec![]
            },
        }
    }

    fn paths(p: &Publication) -> Vec<String> {
        p.files().into_iter().map(|(path, _)| path).collect()
    }

    #[test]
    fn completed_writes_lists_and_timeouts_only_when_present() {
        assert_eq!(
            paths(&publication(OutcomeKind::Completed, false)),
            [
                "README.md",
                "summary.toml",
                "missed.txt",
                "located/missed.txt"
            ]
        );
        let with = publication(OutcomeKind::Completed, true);
        assert_eq!(paths(&with).len(), 6);
        let missed = with
            .files()
            .into_iter()
            .find(|(p, _)| p == "missed.txt")
            .unwrap();
        assert_eq!(missed.1, "a\nb\n");
    }

    #[test]
    fn failures_write_no_lists() {
        for outcome in [OutcomeKind::BaselineFailed, OutcomeKind::ToolFailed] {
            assert_eq!(
                paths(&publication(outcome, true)),
                ["README.md", "summary.toml"]
            );
        }
    }

    #[test]
    fn messages_follow_the_design() {
        assert_eq!(
            publication(OutcomeKind::Completed, false).message(),
            "Mutants of ababab: 2 missed (+1 -0), 10 caught".replace("ababab", "abababa")
        );
        assert_eq!(
            publication(OutcomeKind::BaselineFailed, false).message(),
            "Mutants of abababa: baseline failed"
        );
        assert_eq!(
            publication(OutcomeKind::ToolFailed, false).message(),
            "Mutants of abababa: tool failed"
        );
    }
}
